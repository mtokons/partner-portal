export function getServicePricingByCategory(
  category: WorkflowCategory
): ServicePricing[] {
  return SERVICE_PRICING_DATA.filter(
    (s) => s.workflowCategory === category && s.isActive
  ).sort((a, b) => a.sortOrder - b.sortOrder);
}

export function getServicePricingById(id: string): ServicePricing | undefined {
  return SERVICE_PRICING_DATA.find((s) => s.id === id);
}
